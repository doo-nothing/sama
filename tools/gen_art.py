"""Generate sama_art.h: point tables for the OP-1 page, in units."""
import math, os

def arch(cx, ybase, width, height, n=24):
    w2 = width / 2.0
    c = (w2 * w2 - height * height) / width
    r = w2 - c
    lc, rc = cx - c, cx + c
    a_al = math.atan2(-height, c)
    if a_al < math.pi:
        a_al += 2 * math.pi
    a_ar = math.atan2(-height, -c)
    pts = []
    for i in range(n + 1):
        a = math.pi + (a_al - math.pi) * i / n
        pts.append((lc + r * math.cos(a), ybase + r * math.sin(a)))
    for i in range(n + 1):
        a = a_ar + (0.0 - a_ar) * i / n
        pts.append((rc + r * math.cos(a), ybase + r * math.sin(a)))
    return pts

def ellipse(cx, cy, rx, ry, n=24):
    return [(cx + rx * math.cos(2 * math.pi * i / n), cy + ry * math.sin(2 * math.pi * i / n))
            for i in range(n + 1)]

def star(cx, cy, r, n=8, inner=0.42, rot=math.pi / 8):
    return [(cx + (r if i % 2 == 0 else r * inner) * math.cos(rot + i * math.pi / n),
             cy + (r if i % 2 == 0 else r * inner) * math.sin(rot + i * math.pi / n)) for i in range(n * 2)]

def circle(n=48, r=1000):
    return [(r * math.cos(2 * math.pi * i / n), r * math.sin(2 * math.pi * i / n)) for i in range(n + 1)]

def emit(name, pts, w, f):
    f.write("static const short %s[%d][2] = {\n" % (name, len(pts)))
    for i, (x, y) in enumerate(pts):
        f.write("  {%d,%d}%s" % (round(x), round(y), "," if i < len(pts) - 1 else ""))
        if (i + 1) % 6 == 0:
            f.write("\n")
    f.write("\n};\n")

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "op1-engine", "plugins", "jake.sama", "sama_art.h")
out = os.path.normpath(out)
with open(out, "w") as f:
    f.write("/* generated by mishkat/tools/gen_art.py: the page's point tables, in units */\n")
    f.write("#ifndef SAMA_ART_H\n#define SAMA_ART_H\n")
    emit("ARCH_OUT", arch(160, 117, 128, 103), 320, f)
    emit("ARCH_IN", arch(160, 117, 114, 93), 320, f)
    emit("BOWL", ellipse(160, 81, 22, 7), 320, f)
    emit("RING48", circle(48, 1000), 320, f)
    emit("STAR8", star(0, 0, 1000), 320, f)
    emit("SQ4", [(-1000, -1000), (1000, -1000), (1000, 1000), (-1000, 1000), (-1000, -1000)], 320, f)
    emit("OCT8", [(1000 * math.cos(math.pi / 8 + i * math.pi / 4),
                   1000 * math.sin(math.pi / 8 + i * math.pi / 4)) for i in range(9)], 320, f)
    emit("RAYS", [(1000 * math.cos(math.pi * (1.08 + 0.84 * i / 14)),
                   1000 * math.sin(math.pi * (1.08 + 0.84 * i / 14))) for i in range(15)], 320, f)
    # flame half-widths, tip to base, 25 rows
    fw = []
    for i in range(25):
        t = i / 24.0
        k = math.sin(math.pi * min(1.0, t ** 0.78)) ** 0.9
        fw.append(round(5.5 * k))
    f.write("static const unsigned char FLAME_W[25] = {%s};\n" % ",".join(str(v) for v in fw))
    f.write("#endif\n")
print("wrote", out)
