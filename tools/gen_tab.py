import math, os
out = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                                    "op1-engine", "plugins", "jake.sama", "sama_tab.h"))
with open(out, "w") as f:
    f.write("/* generated by mishkat/tools/gen_tab.py */\n#ifndef SAMA_TAB_H\n#define SAMA_TAB_H\n")
    # delay length in samples x 256 (Q8): 20 ms to 1.2 s, exponential
    f.write("static const int TIMETAB[100] = {\n")
    vals = [round(20e-3 * 44100 * (60.0 ** (i / 99.0)) * 256) for i in range(100)]
    vals[-1] = min(vals[-1], 52920 * 256)
    for i in range(0, 100, 10):
        f.write("  " + ", ".join(str(v) for v in vals[i:i+10]) + ",\n")
    f.write("};\n")
    # one-pole write coefficient, Q15: 32767 at 20 ms down to ~7800 at 1.2 s
    f.write("static const short WLP[100] = {\n")
    co = [round(32767 - (32767 - 7800) * (i / 99.0) ** 0.7) for i in range(100)]
    for i in range(0, 100, 10):
        f.write("  " + ", ".join(str(v) for v in co[i:i+10]) + ",\n")
    f.write("};\n")
    # filter g = tan(pi fc / fs), Q12, 60 Hz .. 9 kHz
    f.write("static const int GTAB[100] = {\n")
    gs = []
    for i in range(100):
        fc = 60.0 * (150.0 ** (i / 99.0))
        gs.append(round(math.tan(math.pi * fc / 44100.0) * 4096))
    for i in range(0, 100, 10):
        f.write("  " + ", ".join(str(v) for v in gs[i:i+10]) + ",\n")
    f.write("};\n")
    # breath rate: phase step per 64-sample block, 0.02 Hz .. 40 Hz
    f.write("static const unsigned int BRTTAB[100] = {\n")
    br = [round((0.02 * (2000.0 ** (i / 99.0))) * 4294967296.0 / (44100.0 / 64.0)) for i in range(100)]
    for i in range(0, 100, 10):
        f.write("  " + ", ".join(str(v) + "u" for v in br[i:i+10]) + ",\n")
    f.write("};\n")
    # a sine, Q15, 256 points: the wavefolder's curve
    f.write("static const short SINTAB[256] = {\n")
    sv = [round(math.sin(2 * math.pi * i / 256) * 32767) for i in range(256)]
    for i in range(0, 256, 12):
        f.write("  " + ", ".join(str(v) for v in sv[i:i+12]) + ",\n")
    f.write("};\n")
    # absorb: a one-pole lowpass in the loop, 18 kHz down to 300 Hz (Q15)
    f.write("static const short ABSTAB[100] = {\n")
    av = [round((1.0 - math.exp(-2 * math.pi * (18000.0 * (300.0 / 18000.0) ** (i / 99.0)) / 44100.0)) * 32767) for i in range(100)]
    for i in range(0, 100, 10):
        f.write("  " + ", ".join(str(v) for v in av[i:i+10]) + ",\n")
    f.write("};\n")
    # the loop's highpass cutoff, 80 Hz .. 1.2 kHz (Q15 one-pole coefficient)
    f.write("static const short TONETAB[100] = {\n")
    tv = [round((1.0 - math.exp(-2 * math.pi * (80.0 * (1200.0 / 80.0) ** (i / 99.0)) / 44100.0)) * 32767) for i in range(100)]
    for i in range(0, 100, 10):
        f.write("  " + ", ".join(str(v) for v in tv[i:i+10]) + ",\n")
    f.write("};\n")
    f.write("#endif\n")
print("wrote", out)
